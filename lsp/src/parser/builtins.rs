/// All built-in names (commands + functions)
pub fn all_builtins() -> &'static HashSet<&'static str> {
    static SET: OnceLock<HashSet<&'static str>> = OnceLock::new();
    SET.get_or_init(|| {
        let mut set = HashSet::default();
        set.extend(COMMANDS.iter().copied());
        set.extend(FUNCTIONS.iter().copied());
        set.extend(PUCHI_COMMANDS.iter().copied());
        set
    })
}

/// Check if a name is a built-in command
pub fn is_builtin_command(name: &str) -> bool {
    let upper = name.to_uppercase();
    COMMANDS.contains(&upper.as_str()) || PUCHI_COMMANDS.contains(&upper.as_str())
}

/// Check if a name is a built-in function
pub fn is_builtin_function(name: &str) -> bool {
    let upper = name.to_uppercase();
    FUNCTIONS.contains(&upper.as_str())
}

/// Check if a name is any built-in
pub fn is_builtin(name: &str) -> bool {
    is_builtin_command(name) || is_builtin_function(name)
}

/// Check if a built-in function returns a string
pub fn returns_str(name: &str) -> bool {
    let upper = name.to_uppercase();
    STR_FUNCTIONS.contains(&upper.as_str())
}

/// Check if a command is prohibited in #FUNCTION/#FUNCTIONS
pub fn not_in_function(name: &str) -> bool {
    let upper = name.to_uppercase();
    NOT_IN_FUNCTION.contains(&upper.as_str())
}

/// Get completion items for all built-ins
pub fn builtin_completions() -> Vec<CompletionItem> {
    let mut items = Vec::new();

    for cmd in COMMANDS {
        items.push(CompletionItem {
            label: cmd.to_string(),
            kind: CompletionItemKind::Function,
            detail: Some("Built-in command".into()),
            documentation: Some(get_command_doc(cmd)),
        });
    }

    for func in FUNCTIONS {
        items.push(CompletionItem {
            label: func.to_string(),
            kind: CompletionItemKind::Function,
            detail: Some("Built-in function".into()),
            documentation: Some(get_function_doc(func)),
        });
    }

    items
}

/// Get completion items for keywords
pub fn keyword_completions() -> Vec<CompletionItem> {
    KEYWORDS
        .iter()
        .map(|kw| CompletionItem {
            label: kw.to_string(),
            kind: CompletionItemKind::Keyword,
            detail: Some("Keyword".into()),
            documentation: Some(get_keyword_doc(kw)),
        })
        .collect()
}

